import enum
from datetime import date, datetime

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    Enum,
    Integer,
    LargeBinary,
    String,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from .database import Base


class ApplicationStatus(str, enum.Enum):
    saved = "Saved"
    applied = "Applied"
    online_assessment = "Online Assessment"
    interview = "Interview"
    offer = "Offer"
    rejected = "Rejected"
    ghosted = "Ghosted"


class Job(Base):
    __tablename__ = "jobs"

    # Internal auto-incrementing primary key (used for API routes, not shown).
    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)

    # "Job Id" column in the grid -> entered by the user (e.g. a req number).
    job_id: Mapped[str | None] = mapped_column(String(100), nullable=True)

    company_name: Mapped[str] = mapped_column(String(255), nullable=False)
    job_link: Mapped[str | None] = mapped_column(Text, nullable=True)
    application_status: Mapped[ApplicationStatus] = mapped_column(
        Enum(ApplicationStatus, name="application_status"),
        default=ApplicationStatus.saved,
        nullable=False,
    )
    used_referral: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    cold_email: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    recruiter_email: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # Auto-set to the current date when the status first becomes "Applied".
    applied_date: Mapped[date | None] = mapped_column(Date, nullable=True)

    # Files are stored directly as docx bytes in Postgres (bytea).
    resume: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    resume_filename: Mapped[str | None] = mapped_column(String(255), nullable=True)

    cover_letter: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    cover_letter_filename: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # JD is entered as text; a .docx is generated from it on download.
    jd_text: Mapped[str | None] = mapped_column(Text, nullable=True)

    # ATS keyword analysis of the JD (JSON string), generated by a local LLM.
    ats_keywords: Mapped[str | None] = mapped_column(Text, nullable=True)

    # JD vs. resume compatibility analysis (JSON string with a score).
    compatibility: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    # Plain Python properties (not mapped columns) consumed by the API schema
    # so the grid can show whether a file is attached without loading bytes.
    @property
    def has_resume(self) -> bool:
        return self.resume is not None

    @property
    def has_cover_letter(self) -> bool:
        return self.cover_letter is not None

    @property
    def has_jd(self) -> bool:
        return bool(self.jd_text)

    @property
    def has_ats(self) -> bool:
        return bool(self.ats_keywords)

    @property
    def has_compatibility(self) -> bool:
        return bool(self.compatibility)
